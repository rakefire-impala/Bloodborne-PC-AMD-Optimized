"""Retry a boss fight after dying in it (launcher: Quality of Life). Generated from the player's own
game files.

How the game does it: a boss's fog gate is a map event that, on the action button, turns the player
toward a point outside the fog and plays the walk through it (2004[14] [10000, point, 101130, 0]),
ending once the boss's defeat flag is on (1003[02] at its start). A region just inside the fog
(3[02] [.., 10000, region]) ends the walk. Each gate has a host event and a client copy; the host's
is the one with action button group 2 or 3.

What this adds, in a mod layer that replaces whole files:
- each map with a boss fog (event/mAA_BB_00_00.emevd.dcx): an event per gate that, while the boss
  lives, waits for the player inside the fog, writes the gate's number to the BITS flags and sets
  ENTERED (src/runtime_retry.c reads and clears it);
- the common event script: per gate, an event that waits for REQUEST with the gate's number in BITS
  and puts the player at the gate's point: a short warp in the gate's map, otherwise a respawn
  point warp (it takes lamps only) to a lamp of that map and, on arrival (ARRIVE), the short warp;
- boss_retry.txt beside dvdroot_ps4: the gates, the flags and the boss names, for the port
  (BB_BOSS_RETRY). The port asks after a death in a major boss fight (a boss bar named by a boss,
  not an NPC hunter) whether to retry it, and sets BITS and REQUEST.
Chalice dungeons (m29) are generated by the game and have no fixed gates.
"""
import struct
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fsformats as F  # noqa: E402

COMMON_EVENTS = 'event/common.emevd.dcx'
RETRY_FILE = 'boss_retry.txt'
PLAYER = 10000
FOG_WALK = 101130               # the animation of walking through a fog gate
DREAM_RESPAWN = 2102950         # the Hunter's Dream's respawn point (its own lamp travel uses it)
WARP_HANDLER = 12107000         # the Dream's per-lamp warp handler: its instances name every lamp
# Event flags shared with the port; 6920-6999 are used by no game file (lamp travel: 6920-6984).
REQUEST, ARRIVE, ENTERED, BITS = 6986, 6987, 6988, 6989
BIT_COUNT = 8
FIRST_EVENT, LAST_EVENT = 7400, 7599   # ours, in common.emevd (7301-7599 are unused there)
MARKER_EVENT = 9950             # + map block base: the gate markers' event IDs in each map
NAMES = 'NPC名'                 # item.msgbnd: the names boss bars show
# Boss bar names (EMEVD 2003[11]) of the bosses themselves; NPC hunters have lower IDs, and the
# chalice hunters and Alfred higher ones (Micolash, 899000, is a boss).
MAJOR_NAMES = range(100000, 899001)
MESSAGE_FOLDERS = {0: 'engus', 1: 'engus', 2: 'frafr', 3: 'spaes', 4: 'deude', 5: 'itait', 6: 'nldnl',
                   7: 'porpt', 8: 'rusru', 12: 'finfi', 13: 'swese', 14: 'dandk', 15: 'norno', 16: 'polpl',
                   17: 'porbr', 18: 'enggb', 19: 'turtr', 20: 'spaar'}
# The prompt's texts: the game has none for this. Russian for Russian, English otherwise.
TEXTS = {'rusru': ('Повторить бой?', 'Повторить', 'Не сейчас'),
         'engus': ('Retry the fight?', 'Retry', 'Not now')}


def ints(*values):
    return struct.pack(f'<{len(values)}i', *values)


def flag_condition(group, on, flag):
    return (3, 0, bytes([group, 1 if on else 0, 0, 0]) + ints(flag))


def set_flag(flag, on):
    return (2003, 2, ints(flag, 1 if on else 0))


class Gate:
    """A boss fog gate: map event, point outside, region inside, defeat flag condition."""

    def __init__(self, path, event, point, inside, defeated):
        self.path, self.event, self.point, self.inside, self.defeated = path, event, point, inside, defeated
        name = path.split('/')[-1]               # mAA_BB_00_00.emevd.dcx
        self.area, self.block = int(name[1:3]), int(name[4:6])
        self.defeat_flag = struct.unpack_from('<i', defeated, 4)[0]
        self.lamp = None


def find_gates(events: F.Emevd, path):
    """The host gates of a map's event script."""
    gates = []
    for eid, start, count, *_ in events.events:
        ins = [(events.ins[i][0], events.ins[i][1], events.ins_args(i)) for i in range(start, start + count)]
        for at, (bank, iid, args) in enumerate(ins):
            if (bank, iid) != (2004, 14) or len(args) != 16:
                continue
            chr_, point, animation, _ = struct.unpack('<4i', args)
            if chr_ != PLAYER or animation != FOG_WALK:
                continue
            ends = [a for b, i, a in ins[:at] if (b, i) == (1003, 2) and len(a) == 8]
            buttons = [a for b, i, a in ins[:at] if (b, i) == (3, 24) and len(a) == 12]
            inside = [a for b, i, a in ins[at:] if (b, i) == (3, 2) and len(a) == 12
                      and struct.unpack_from('<i', a, 4)[0] == PLAYER]
            # The client copy waits in group 1 and is left out.
            if not ends or not buttons or not inside or buttons[0][0] < 2:
                continue
            gates.append(Gate(path, eid, point, struct.unpack_from('<i', inside[0], 8)[0], ends[0]))
    return gates


def lamps(dream_events: F.Emevd):
    """{(area, block): respawn point} of the first lamp of each map the Dream's headstones list."""
    out = {(21, 0): DREAM_RESPAWN}
    for bank, iid, args in dream_events.event_ins(0):
        if (bank, iid) == (2000, 0) and len(args) == 20:
            _slot, event, _flag, _headstone, region = struct.unpack('<5i', args)
            if event == WARP_HANDLER:
                out.setdefault((region // 100000, region // 10000 % 10), region)
    return out


def marker_event(gate, number):
    """Map event: while the boss lives, the player inside the fog marks the gate as entered."""
    bits = [set_flag(BITS + k, number >> k & 1) for k in range(BIT_COUNT)]
    return [
        (1003, 2, gate.defeated),                                      # end once the boss is dead
        (3, 2, bytes([0, 1, 0, 0]) + ints(PLAYER, gate.inside)),       # wait: player inside the fog
        *bits,
        set_flag(ENTERED, 1),
        (3, 2, bytes([0, 0, 0, 0]) + ints(PLAYER, gate.inside)),       # wait: player out of it again
        (1000, 4, ints(1)),                                            # restart
    ]


def wait_for(flag, number):
    """Wait until flag is on and BITS hold number, all at once (condition group 1)."""
    return [flag_condition(1, True, flag),
            *[flag_condition(1, number >> k & 1, BITS + k) for k in range(BIT_COUNT)],
            (0, 0, bytes([0, 1, 1, 0]))]


def retry_events(gate, number, end_in_coop):
    here = bytes([0, 0, gate.area, gate.block])      # end unless in the gate's map
    elsewhere = bytes([0, 1, gate.area, gate.block])  # end in the gate's map
    short_warp = (2004, 3, ints(PLAYER, 1, gate.point, -1))
    events = [
        [end_in_coop, (1003, 8, here), *wait_for(REQUEST, number), set_flag(REQUEST, False), short_warp,
         (1000, 4, ints(1))],
        [(1003, 8, here), *wait_for(ARRIVE, number), set_flag(ARRIVE, False),
         (1001, 0, struct.pack('<f', 1.0)), short_warp, (1000, 4, ints(1))],
    ]
    if gate.lamp is not None:
        events.append([end_in_coop, (1003, 8, elsewhere), *wait_for(REQUEST, number), set_flag(REQUEST, False),
                       set_flag(ARRIVE, True), (2003, 49, ints(gate.lamp))])
    return events


def boss_names(source, language):
    """{name ID: text} of the major bosses, in the game language (English if unavailable)."""
    folder = MESSAGE_FOLDERS.get(language, 'engus')
    for name in dict.fromkeys((folder, 'engus')):
        try:
            bnd = F.Bnd4(F.Dcx(source(f'msg/{name}/item.msgbnd.dcx')).data)
        except OSError:
            continue
        for path, data in bnd.files:
            if path and path.replace('\\', '/').split('/')[-1].split('.')[0] == NAMES:
                return {k: v for k, v in F.fmg_texts(data).items() if k in MAJOR_NAMES and v}, name
    raise ValueError('no NPC names')


def write_file(path: Path, gates, names, texts):
    """The port's list, tab separated, UTF-8."""
    def clean(text):
        return text.replace('\t', ' ').replace('\n', ' ').strip()
    lines = [f'flags\t{REQUEST}\t{ENTERED}\t{BITS}\t{BIT_COUNT}',
             'texts\t' + '\t'.join(clean(t) for t in texts)]
    lines += [f'gate\t{n}\t{g.defeat_flag}\t{g.area}\t{g.block}\t{1 if g.lamp else 0}' for n, g in enumerate(gates)]
    lines += [f'boss\t{k}\t{clean(v)}' for k, v in sorted(names.items())]
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def generate(source, out: Path, language=1):
    """source(relative path) -> bytes of the file in effect (mods and earlier generated files
    included). Writes the layer under out/dvdroot_ps4 and the list to out/boss_retry.txt;
    returns the number of gates."""
    root = out / 'dvdroot_ps4'
    dream = lamps(F.Emevd(F.Dcx(source('event/m21_00_00_00.emevd.dcx')).data))
    gates, maps = [], []
    for path in source.event_scripts():
        name = path.split('/')[-1]
        if not name.startswith('m') or name.startswith('m29'):
            continue
        dcx = F.Dcx(source(path))
        events = F.Emevd(dcx.data)
        found = find_gates(events, path)
        if found:
            maps.append((path, dcx, events, found))
            gates += found
    if not gates:
        raise ValueError('no boss fog gates')
    if len(gates) > min(1 << BIT_COUNT, (LAST_EVENT - FIRST_EVENT + 1) // 3):
        raise ValueError(f'{len(gates)} boss gates do not fit')
    common_dcx = F.Dcx(source(COMMON_EVENTS))
    common = F.Emevd(common_dcx.data)
    template = common.event_ins(7200)  # the game's lamp travel starts with "end in co-op"
    if not template or template[0][:2] != (1003, 6):
        raise ValueError('unexpected lamp travel event 7200')
    number = 0
    for path, dcx, events, found in maps:
        base = found[0].event - found[0].event % 10000 + MARKER_EVENT
        for gate in found:
            gate.lamp = dream.get((gate.area, gate.block))
            eid = base
            while events.event(eid) is not None:
                eid += 1
            events.add_event(eid, marker_event(gate, number))
            events.append_to_event(0, [(2000, 0, ints(0, eid, 0))])
            for k, instructions in enumerate(retry_events(gate, number, template[0])):
                common.add_event(FIRST_EVENT + 3 * number + k, instructions)
                common.append_to_event(0, [(2000, 0, ints(0, FIRST_EVENT + 3 * number + k, 0))])
            number += 1
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_bytes(dcx.write(events.write()))
    (root / COMMON_EVENTS).parent.mkdir(parents=True, exist_ok=True)
    (root / COMMON_EVENTS).write_bytes(common_dcx.write(common.write()))
    names, folder = boss_names(source, language)
    write_file(out / RETRY_FILE, gates, names, TEXTS.get(folder, TEXTS['engus']))  # last: the layer is complete
    return len(gates)
